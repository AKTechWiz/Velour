#!/usr/bin/env node
// Import listings from incoming/listings-template.csv -> lib/generated-products.ts
// Usage: node scripts/import-listings.mjs
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { execFileSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const csvPath = path.join(root, "incoming", "listings-template.csv");
const outTs = path.join(root, "lib", "generated-products.ts");
const imgIn = path.join(root, "incoming", "images");
const imgOut = path.join(root, "public", "images", "products");

if (!existsSync(csvPath)) {
  console.error(`CSV file not found at ${csvPath}`);
  process.exit(1);
}

if (!existsSync(imgIn)) {
  mkdirSync(imgIn, { recursive: true });
}

const csv = readFileSync(csvPath, "utf-8");
const lines = csv.split(/\r?\n/).filter((l) => l.trim().length > 0);
if (lines.length <= 1) {
  console.log("No listings found in CSV template. Generated empty product array.");
  const emptyTs = `// AUTO-GENERATED by scripts/import-listings.mjs — do not hand-edit.\nimport type { Product } from "./types";\n\nexport const GENERATED_PRODUCTS: Product[] = [];\n`;
  writeFileSync(outTs, emptyTs);
  process.exit(0);
}

const header = lines[0].split(",").map((h) => h.trim());

function parseRow(line) {
  // Parse CSV line handling quoted cells
  const cells = [];
  let cur = "", inQ = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === '"') {
      if (inQ && line[i + 1] === '"') {
        cur += '"';
        i++;
      } else {
        inQ = !inQ;
      }
      continue;
    }
    if (ch === "," && !inQ) {
      cells.push(cur);
      cur = "";
      continue;
    }
    cur += ch;
  }
  cells.push(cur);
  return Object.fromEntries(header.map((h, i) => [h, (cells[i] ?? "").trim()]));
}

function slugify(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

function optimize(file) {
  if (!file) return null;
  const src = path.join(imgIn, file);
  if (!existsSync(src)) return null;
  if (!existsSync(imgOut)) mkdirSync(imgOut, { recursive: true });
  const dst = path.join(imgOut, file);
  try {
    // macOS built-in image tool; falls back to a plain copy elsewhere
    execFileSync("sips", ["-Z", "1600", "-s", "format", "jpeg", src, "--out", dst], { stdio: "ignore" });
  } catch {
    writeFileSync(dst, readFileSync(src));
  }
  return `/images/products/${file}`;
}

const products = lines.slice(1).map((line) => {
  const r = parseRow(line);
  if (!r.name) return null;
  const img1 = optimize(r.image1);
  const img2 = optimize(r.image2);
  const images = [img1, img2].filter(Boolean);
  if (images.length === 0) {
    images.push("/images/products/wool-coat-1.jpg");
  }
  return {
    id: slugify(r.name),
    slug: slugify(r.name),
    name: r.name,
    category: r.category === "men" ? "men" : "women",
    subcategory: r.subcategory || "Tops",
    price: Number(r.price) || 0,
    ...(r.compareAtPrice ? { compareAtPrice: Number(r.compareAtPrice) } : {}),
    description: r.description,
    sizes: r.sizes ? r.sizes.split("|").map((s) => s.trim()) : ["XS", "S", "M", "L", "XL"],
    images,
    featured: r.featured?.toLowerCase() === "yes",
    isNew: r.isNew?.toLowerCase() === "yes",
    trending: r.trending?.toLowerCase() === "yes",
  };
}).filter(Boolean);

const body = JSON.stringify(products, null, 2);
const ts = `// AUTO-GENERATED by scripts/import-listings.mjs — do not hand-edit.
import type { Product } from "./types";

export const GENERATED_PRODUCTS: Product[] = ${body};
`;

writeFileSync(outTs, ts);
console.log(`Imported ${products.length} listing(s) -> lib/generated-products.ts`);
